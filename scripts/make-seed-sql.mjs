/* ==========================================================================
   WBA — turns scripts/seed-posts.json into supabase/seed-posts.sql.

   The JSON is what the local test build reads; the SQL is what you paste
   into Supabase so the same placeholder posts become real, editable rows.
   Generating one from the other keeps them from drifting apart.

     node scripts/make-seed-sql.mjs
   ========================================================================== */

import { readFileSync, writeFileSync, mkdirSync } from 'fs';

const posts = JSON.parse(readFileSync('scripts/seed-posts.json', 'utf8'));

/* Postgres string literal: double up single quotes. */
const q = v => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = a => (a && a.length ? `array[${a.map(q).join(',')}]::text[]` : `'{}'::text[]`);

const rows = posts.map(p => {
  /* body is a text column holding the block JSON, exactly as the admin saves it */
  const body = JSON.stringify(p.body);
  return `  (${q(p.slug)}, ${q(p.title)}, ${q(p.excerpt)}, ${q(p.cover_image)}, ${q(p.category)}, ` +
         `${arr(p.tags)}, ${q(body)}, ${p.featured ? 'true' : 'false'}, ${q(p.author || 'WBA')}, ` +
         /* draft, not published — these are starting points to edit in the
            admin, not copy anyone should find on the live site */
         `'draft', ${q(p.published_at)}::timestamptz)`;
}).join(',\n');

const sql = `-- ==========================================================================
-- WBA — placeholder Feed posts.
-- GENERATED by scripts/make-seed-sql.mjs — edit scripts/seed-posts.json and
-- re-run that script rather than editing this file by hand.
--
-- Run supabase/schema.sql FIRST (it adds the \`featured\` column).
-- Then paste this into Supabase -> SQL Editor -> Run.
--
-- These land as DRAFTS. Open each one in the admin, rewrite it, and switch
-- Status to Published when it's yours. Nothing appears on the live site until
-- you do, and until the Build feed workflow runs.
--
-- Safe to re-run: it matches on slug and updates rather than duplicating.
-- Delete them later with:
--   delete from public.posts where slug in (${posts.map(p => `'${p.slug}'`).join(', ')});
-- ==========================================================================

insert into public.posts
  (id, slug, title, excerpt, cover_image, category, tags, body, featured, author, status, published_at, updated_at)
select
  gen_random_uuid(), v.slug, v.title, v.excerpt, v.cover_image, v.category, v.tags, v.body,
  v.featured, v.author, v.status, v.published_at, now()
from (values
${rows}
) as v(slug, title, excerpt, cover_image, category, tags, body, featured, author, status, published_at)
on conflict (slug) do update set
  title       = excluded.title,
  excerpt     = excluded.excerpt,
  cover_image = excluded.cover_image,
  category    = excluded.category,
  tags        = excluded.tags,
  body        = excluded.body,
  featured    = excluded.featured,
  author      = excluded.author,
  status      = excluded.status,
  updated_at  = now();
`;

mkdirSync('supabase', { recursive: true });
writeFileSync('supabase/seed-posts.sql', sql);
console.log(`Wrote supabase/seed-posts.sql (${posts.length} posts).`);
